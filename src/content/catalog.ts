// Fonte única de números, títulos e ordem das aulas. Os títulos são os de
// docs/ai-engineering-roadmap.md, em inglês (AD-009); catalog.test.ts compara os dois.

type LessonRow = [title: string, durationMin: number, level: Level];

const B: Level = "beginner";
const I: Level = "intermediate";
const A: Level = "advanced";

function defineModule(id: ModuleId, title: string, rows: LessonRow[]): ModuleMeta {
  return {
    id,
    title,
    lessons: rows.map(([lessonTitle, durationMin, level], index) => {
      const lessonNumber = String(index + 1).padStart(2, "0");
      return {
        id: `${id}-${lessonNumber}`,
        module: id,
        number: `${id}.${lessonNumber}`,
        title: lessonTitle,
        durationMin,
        level,
      };
    }),
  };
}

